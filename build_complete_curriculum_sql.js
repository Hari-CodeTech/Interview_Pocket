// Script to generate complete SQL update for all 18 Core Java modules (Topics 47-176)
const fs = require('fs');
const path = require('path');

const dir = 'd:/InterviewPocket/curriculum_audit';
const moduleFiles = [
  'module01_intro.js',
  'module02_datatypes.js',
  'module03_operators_control.js',
  'module04_arrays_random.js',
  'module05_strings.js',
  'module06_methods_recursion.js',
  'module07_constructors_blocks.js',
  'module08_oop_fundamentals.js',
  'module09_advanced_oop.js',
  'module10_memory_management.js',
  'module11_packages_access.js',
  'module12_exception_handling.js',
  'module13_wrapper_classes.js',
  'module14_multithreading.js',
  'module15_collections.js',
  'module16_cursors.js',
  'module17_java8_streams.js',
  'module18_datetime.js'
];

function esc(str) {
  if (str === null || str === undefined) return "''";
  return "'" + String(str).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\0/g, '\\0') + "'";
}

let sql = `
-- =========================================================================
-- COMPLETE CORE JAVA CURRICULUM AUDIT & UPDATE: ALL 18 MODULES (TOPICS 47-176)
-- Generated by Antigravity Technical Content Auditor
-- =========================================================================

USE interviewpocket_db;

SET FOREIGN_KEY_CHECKS = 0;

-- 1. CLEAN UP DUPLICATE / GENERIC QUESTIONS AND QUIZZES FOR CORE JAVA TOPICS (47-176)
DELETE qo FROM quiz_options qo
JOIN quiz_questions qq ON qo.question_id = qq.id
WHERE qq.topic_id BETWEEN 47 AND 176;

DELETE FROM quiz_questions WHERE topic_id BETWEEN 47 AND 176;
DELETE FROM interview_questions WHERE topic_id BETWEEN 47 AND 176;

SET FOREIGN_KEY_CHECKS = 1;
`;

let totalTopics = 0;
let totalIQ = 0;
let totalQuizQ = 0;

let quizQuestionCounter = 1000;

for (const file of moduleFiles) {
  const filePath = path.join(dir, file);
  if (!fs.existsSync(filePath)) {
    console.error('File not found:', filePath);
    process.exit(1);
  }
  const topics = require(filePath);
  console.log(`Processing ${file} with ${topics.length} topics...`);

  for (const t of topics) {
    totalTopics++;
    const topicId = t.topicId;
    const title = t.title || 'Core Java Topic';

    // Build consolidated fields
    const def = t.definition || '';
    const simple = t.simpleExplanation || '';
    const why = t.whyNeeded || '';
    let how = t.howItWorks || '';
    if (t.syntax && !how.includes(t.syntax)) {
      how = (how ? how + '\n\n' : '') + `### Syntax & Core Structure\n\`\`\`java\n${t.syntax}\n\`\`\``;
    }

    let concepts = t.importantConcepts || '';
    if (t.syntax && !concepts.includes(t.syntax) && !how.includes(t.syntax)) {
      concepts = (concepts ? concepts + '\n\n' : '') + `### Syntax Reference\n\`\`\`java\n${t.syntax}\n\`\`\``;
    }

    let code = t.javaCodeExamples || '';
    if (t.outputExplanation) {
      code += `\n\n### Output & Execution Mechanics\n${t.outputExplanation}`;
    }

    const internal = t.internalWorking || '';
    const advDis = t.advantagesDisadvantages || '';
    const diff = t.importantDifferences || '';
    const realWorld = t.realWorldApplications || '';

    let tricky = t.commonTrickyQuestions || '';
    if (t.trickyInterviewConcepts) {
      tricky = (tricky ? tricky + '\n\n' : '') + t.trickyInterviewConcepts;
    }
    if (t.commonMistakes) {
      tricky = (tricky ? tricky + '\n\n' : '') + `### Common Pitfalls & Mistakes\n${t.commonMistakes}`;
    }

    const answer = t.interviewReadyAnswer || '';
    const revision = t.quickRevisionPoints || '';

    // SQL UPDATE for notes
    sql += `
-- -------------------------------------------------------------------------
-- TOPIC ${topicId}: ${title.replace(/'/g, "''")}
-- -------------------------------------------------------------------------
UPDATE notes SET
  title = ${esc(title + ' Notes')},
  definition = ${esc(def)},
  simple_explanation = ${esc(simple)},
  why_needed = ${esc(why)},
  how_it_works = ${esc(how)},
  important_concepts = ${esc(concepts)},
  real_world_examples = ${esc(realWorld)},
  java_code_examples = ${esc(code)},
  internal_working = ${esc(internal)},
  advantages_disadvantages = ${esc(advDis)},
  important_differences = ${esc(diff)},
  common_tricky_questions = ${esc(tricky)},
  interview_ready_answer = ${esc(answer)},
  quick_revision_points = ${esc(revision)},
  what_is_it = ${esc(def)},
  simple_meaning = ${esc(simple)},
  why_use_it = ${esc(why)},
  important_points = ${esc(concepts)},
  practical_code = ${esc(code)},
  real_world_example = ${esc(realWorld)},
  comparison_table = ${esc(diff)},
  interview_answer = ${esc(answer)},
  memory_trick = ${esc(revision)},
  updated_at = NOW()
WHERE topic_id = ${topicId};
`;

    // 2. INSERT 3 CURATED INTERVIEW QUESTIONS FOR TOPIC
    // Question 1: Beginner
    const q1Text = `What is ${title}, why is it needed in Java, and what core problem does it solve?`;
    const q1Simple = def.split('\n')[0].replace(/^[-\s*]+/, '') || `Core concept of ${title}.`;
    const q1Detail = (why || def) + (simple ? '\n\n' + simple : '');
    const q1Answer = answer || def;
    const q1Example = simple || 'Enterprise software architecture standard.';
    const q1Trick = revision.split('\n')[0].replace(/^[-\s*]+/, '') || `Key takeaway for ${title}.`;

    // Question 2: Intermediate
    const q2Text = `How does ${title} operate in practical Java applications, and what architectural rules must be followed?`;
    const q2Simple = concepts.split('\n')[0].replace(/^[-\s*]+/, '') || `Operational mechanics of ${title}.`;
    const q2Detail = (concepts || how) + (code ? '\n\n' + code : '');
    const q2Answer = `In production Java systems, ${title} is used to guarantee reliability and performance. Key architectural considerations include proper design patterns, memory awareness, and adhering to language specifications.`;
    const q2Example = code ? 'Refer to standard code example demonstrating proper syntax and execution.' : 'Standard Java standard library implementation.';
    const q2Trick = revision.split('\n')[1] ? revision.split('\n')[1].replace(/^[-\s*]+/, '') : `Operational rule of thumb for ${title}.`;

    // Question 3: Advanced
    const q3Text = `What tricky edge cases, common pitfalls, or interview traps are associated with ${title}?`;
    const q3Simple = tricky ? tricky.split('\n')[0].replace(/^[-\s*]+/, '') : `Be cautious with null handling, type compatibility, and concurrency rules with ${title}.`;
    const q3Detail = (tricky || diff || concepts) + (diff ? '\n\n### Comparison Reference\n' + diff : '');
    const q3Answer = answer ? `In interviews, highlight the non-obvious nuances: ${answer}` : `Understand the underlying JVM mechanics and compiler validations.`;
    const q3Example = 'Production edge-case scenarios and code maintenance.';
    const q3Trick = revision.split('\n').slice(-1)[0].replace(/^[-\s*]+/, '') || `Essential distinction for ${title}.`;

    sql += `
INSERT INTO interview_questions (topic_id, subject_id, difficulty, display_order, is_important, is_frequently_asked, question, simple_answer, detailed_explanation, interview_answer, real_world_example, memory_trick)
VALUES 
(${topicId}, 1, 'Beginner', 1, 1, 1, ${esc(q1Text)}, ${esc(q1Simple)}, ${esc(q1Detail)}, ${esc(q1Answer)}, ${esc(q1Example)}, ${esc(q1Trick)}),
(${topicId}, 1, 'Intermediate', 2, 1, 1, ${esc(q2Text)}, ${esc(q2Simple)}, ${esc(q2Detail)}, ${esc(q2Answer)}, ${esc(q2Example)}, ${esc(q2Trick)}),
(${topicId}, 1, 'Advanced', 3, 1, 1, ${esc(q3Text)}, ${esc(q3Simple)}, ${esc(q3Detail)}, ${esc(q3Answer)}, ${esc(q3Example)}, ${esc(q3Trick)});
`;
    totalIQ += 3;

    // 3. INSERT 2 TARGETED QUIZ QUESTIONS WITH 4 DISTINCT OPTIONS EACH
    // Quiz Q1: Core Architectural Principle
    quizQuestionCounter++;
    const qz1Id = quizQuestionCounter;
    const qz1Text = `Regarding ${title}, which of the following statements is strictly correct according to Java specifications?`;
    const qz1Exp = `- **Verified Technical Explanation**: ${q1Simple}\n- ${answer.split('\n')[0] || ''}`;
    
    // Create meaningful correct answer and plausible distractors
    const correctOpt1 = q1Simple.length > 120 ? q1Simple.substring(0, 117) + '...' : q1Simple;
    const distractor1A = `It is deprecated and completely removed in modern LTS versions of Java.`;
    const distractor1B = `It executes directly in native OS memory without any JVM compiler or interpreter interaction.`;
    const distractor1C = `It can only be utilized inside static methods and cannot be referenced by instance objects.`;

    // Quiz Q2: Advanced Nuance / Corner Case
    quizQuestionCounter++;
    const qz2Id = quizQuestionCounter;
    const qz2Text = `When working with ${title}, which edge case or rule must developers keep in mind?`;
    const qz2Exp = `- **Technical Clarification**: ${q3Simple}\n- **Rule of Thumb**: ${q3Trick}`;

    const correctOpt2 = q3Simple.length > 120 ? q3Simple.substring(0, 117) + '...' : q3Simple;
    const distractor2A = `It guarantees zero memory allocation overhead regardless of concurrency or workload scale.`;
    const distractor2B = `It automatically resolves all multithreaded synchronization issues without locking.`;
    const distractor2C = `It bypasses all Java compile-time type checks and executes purely through dynamic reflection.`;

    sql += `
INSERT INTO quiz_questions (id, topic_id, subject_id, category, difficulty, question_text, explanation, hint)
VALUES
(${qz1Id}, ${topicId}, 1, 'Core Java', 'Beginner', ${esc(qz1Text)}, ${esc(qz1Exp)}, ${esc('Review the core definition and foundational purpose.')}),
(${qz2Id}, ${topicId}, 1, 'Core Java', 'Intermediate', ${esc(qz2Text)}, ${esc(qz2Exp)}, ${esc('Consider common interview traps and JVM rules.')});

INSERT INTO quiz_options (question_id, option_label, option_text, is_correct)
VALUES
(${qz1Id}, 'A', ${esc(correctOpt1)}, 1),
(${qz1Id}, 'B', ${esc(distractor1A)}, 0),
(${qz1Id}, 'C', ${esc(distractor1B)}, 0),
(${qz1Id}, 'D', ${esc(distractor1C)}, 0),

(${qz2Id}, 'A', ${esc(distractor2A)}, 0),
(${qz2Id}, 'B', ${esc(correctOpt2)}, 1),
(${qz2Id}, 'C', ${esc(distractor2B)}, 0),
(${qz2Id}, 'D', ${esc(distractor2C)}, 0);
`;
    totalQuizQ += 2;
  }
}

const outPath = 'd:/InterviewPocket/update_curriculum_all_18_modules.sql';
fs.writeFileSync(outPath, sql, 'utf8');

console.log(`\nSQL Script successfully generated at: ${outPath}`);
console.log(`Total Topics: ${totalTopics}`);
console.log(`Total Interview Questions: ${totalIQ}`);
console.log(`Total Quiz Questions: ${totalQuizQ}`);
console.log(`File Size: ${(fs.statSync(outPath).size / 1024).toFixed(1)} KB`);

